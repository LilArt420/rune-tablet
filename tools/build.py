#!/usr/bin/env python3
"""Build client/index.js: the Rune Tablet window's data plus tools/plugin.js.

The data comes from the client's own Rune tables (System/Rune, read from
ROenglishRE's SystemEN/Rune for the English names), the same tables the
server's Rune Tablet NPC is generated from (rathena tools/world_sync/rune_tablet.py),
so rune and set ids, materials, upgrade costs and chances match it.

usage: build.py <SystemEN/Rune folder> --rathena <rathena checkout>
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('rune_dir')
    ap.add_argument('--rathena', required=True)
    a = ap.parse_args()
    ws = os.path.join(os.path.abspath(a.rathena), 'tools', 'world_sync')
    sys.path.insert(0, ws)
    sys.path.insert(1, os.path.join(ws, '..', 'regional_items'))
    import luadata
    import rune_tablet as rt

    R = a.rune_dir
    G = luadata.run([os.path.join(R, f + '.lub') for f in
                     ('runesystemid', 'rune_info', 'runeset_info', 'runeset_reward', 'runeSystem_table')], 'cp949')
    ids = {k: G.get(k) or {} for k in ('RUNEIDTBL', 'RUNESETIDTBL', 'RUNETAGIDTBL')}
    rdesc = rt.text_tables(os.path.join(R, 'desc.lub'), ids).get('Runetbl_desc') or {}
    sdesc = rt.text_tables(os.path.join(R, 'set_desc.lub'), ids).get('RuneSettbl_desc') or {}
    itemlist = G.get('RuneTable_itemList') or {}

    def mats(idx):
        return [[r.get(1), r.get(2)] for r in rt.lines_of(itemlist.get(idx)) if r.get(1)]

    runes = []
    for tag in sorted(G.get('Runetbl_info') or {}):
        for rid, r in sorted(G['Runetbl_info'][tag].items()):
            runes.append({'id': rid, 'tag': tag, 'res': str(r.get('Rune_Res') or '').lower(),
                          'name': ((rdesc.get(tag) or {}).get(rid) or {}).get('Rune_DisplayName') or r.get('Rune_Res'),
                          'mats': mats(r.get('Rune_ActiveList'))})
    sets = []
    for tag in sorted(G.get('RuneSettbl_info') or {}):
        for sid, s in sorted(G['RuneSettbl_info'][tag].items()):
            d = (sdesc.get(tag) or {}).get(sid) or {}
            desc = d.get('RuneSetDescription') or {}
            t, tf = s.get('RuneSet_UpGrade_Percentage_table'), s.get('RuneSet_UpGrade_Percentage_table_Fail')
            sets.append({
                'id': sid, 'tag': tag, 'res': str(s.get('RuneSetRes') or '').lower(),
                'name': d.get('RuneSetDisplayName') or s.get('RuneSetRes'),
                'slots': [v for v in rt.lines_of(s.get('RuneSet_SlotList'))],          # 6 slots, 0 = empty
                'ups': [mats(i) for i in rt.lines_of(s.get('RuneSet_UpGradeList'))],     # level 1..15
                'rate': [(G['GradeTable'].get(t) or {}).get(l, 0) for l in range(1, 16)],
                'fail': [(G['GradeTable_Fail'].get(tf) or {}).get(l, 0) for l in range(1, 16)],
                'desc': [[n, [str(x) for x in (rt.lines_of(desc[n]) if isinstance(desc[n], dict) else desc[n])]]
                         for n in sorted(desc)],
            })
    data = {'tags': {str(k): v for k, v in rt.TAGS.items()}, 'runes': runes, 'sets': sets}
    plugin = open(os.path.join(HERE, 'plugin.js'), encoding='utf-8').read()
    out = os.path.join(HERE, '..', 'client', 'index.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as o:
        o.write('// GENERATED by tools/build.py from the client\'s Rune tables and tools/plugin.js. Edit those.\n')
        o.write('const DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n\n')
        o.write(plugin)
    print('runes %d, sets %d -> %s (%d KB)' % (len(runes), len(sets), out, os.path.getsize(out) // 1024))


if __name__ == '__main__':
    main()
